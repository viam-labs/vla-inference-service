"""Export pinned requirement files from uv.lock for the lazy policy install.

Writes, into OUT_DIR:
  core.txt    the project's core dependencies (installed by setup.sh)
  base.txt    torch + LeRobot without LeRobot extras, minus core
  <type>.txt  one per TYPE_EXTRAS entry: that extra minus core and base

Files are disjoint by package name. No index lines are emitted: the installer
sets UV_TORCH_BACKEND=cu128 on Linux instead (an --emit-index-url export is
unresolvable). Usage: uv run --no-project python tools/export_requirements.py OUT_DIR
"""

from __future__ import annotations

import re
import subprocess
import sys
from pathlib import Path

# Must match the extras in pyproject.toml and the file names in
# vla/policy/installer.py's TYPE_FILES.
TYPE_EXTRAS = ("smolvla", "evo1", "diffusion", "pi", "cosmos3")

_NAME = re.compile(r"^\s*([A-Za-z0-9][A-Za-z0-9._-]*)")


def package_name(line: str) -> str:
    match = _NAME.match(line)
    if not match:
        raise ValueError(f"not a requirement line: {line!r}")
    return re.sub(r"[-_.]+", "-", match.group(1)).lower()


def requirement_lines(text: str) -> list[str]:
    return [
        line.strip()
        for line in text.splitlines()
        if line.strip() and not line.lstrip().startswith("#") and not line.startswith((" ", "\t"))
    ]


def subtract(lines: list[str], names: set[str]) -> list[str]:
    return [line for line in lines if package_name(line) not in names]


def checked_subtract(lines: list[str], kept: list[str], label: str) -> list[str]:
    """subtract() by name, but refuse if a dropped package's lines differ from the kept copy."""
    for name in {package_name(l) for l in lines} & {package_name(l) for l in kept}:
        mine = {l for l in lines if package_name(l) == name}
        theirs = {l for l in kept if package_name(l) == name}
        if mine != theirs:
            raise ValueError(f"{label}: {name} differs from core/base: {sorted(mine)} vs {sorted(theirs)}")
    return subtract(lines, {package_name(l) for l in kept})


def _uv_export(project: Path, extra: str | None) -> list[str]:
    cmd = [
        "uv", "export", "--frozen", "--no-hashes", "--no-annotate", "--no-header",
        "--no-emit-project", "--no-dev", "--format", "requirements.txt",
    ]
    if extra:
        cmd += ["--extra", extra]
    out = subprocess.run(cmd, cwd=project, check=True, stdout=subprocess.PIPE, text=True).stdout
    return requirement_lines(out)


def _write(path: Path, lines: list[str]) -> None:
    header = "# Generated by tools/export_requirements.py from uv.lock. Do not edit.\n"
    path.write_text(header + "".join(f"{line}\n" for line in lines))


def export(out_dir: Path, project: Path) -> None:
    out_dir.mkdir(parents=True, exist_ok=True)
    core = _uv_export(project, None)
    base = checked_subtract(_uv_export(project, "base"), core, "base")
    _write(out_dir / "core.txt", core)
    _write(out_dir / "base.txt", base)
    for extra in TYPE_EXTRAS:
        _write(out_dir / f"{extra}.txt", checked_subtract(_uv_export(project, extra), core + base, extra))


if __name__ == "__main__":
    if len(sys.argv) != 2:
        sys.exit("usage: export_requirements.py OUT_DIR")
    export(Path(sys.argv[1]), project=Path(__file__).resolve().parents[1])
